/**
 * @file user_launch_service_client.h
 *
 * @brief The definition of the privileged launch service client.
 * @since 7.1
 * @version 7.1
 */

#ifndef USER_LAUNCH_SERVICE_H
#define USER_LAUNCH_SERVICE_H

#include <memory>
#include <optional>
#include <vector>

#include "user_launch_service_client_callback.h"
#include "user_launch_service_client_defines.h"

namespace OHOS {
namespace UserIam {
namespace UserAuth {
/**
 * @brief User launch service client.
 *
 * Provides the ability to register, query, and manage launch services.
 */
class UserLaunchServiceClient {
public:
    /**
     * @brief Get the UserLaunchServiceClient instance.
     *
     * @return The UserLaunchServiceClient instance.
     */
    static UserLaunchServiceClient &GetInstance();

    /**
     * @brief Deconstructor.
     */
    virtual ~UserLaunchServiceClient() = default;

    /**
     * @brief Register launch services.
     *
     * @param serviceList List of launch service registration info.
     * @param callback Callback to receive the result and registered service infos.
     */
    virtual void RegisterLaunchService(const std::vector<LaunchServiceRegisterInfo> &serviceList,
        const std::shared_ptr<LaunchServiceListCallback> &callback) = 0;

    /**
     * @brief Unregister a specific launch service by key.
     *
     * @param key Launch service key (uid, serviceName, moduleName).
     * @param callback Callback to receive the result.
     */
    virtual void UnRegisterLaunchService(int32_t uid, const std::optional<LaunchServiceKey> &key,
        const std::shared_ptr<LaunchServiceCallback> &callback) = 0;

    /**
     * @brief Query the detailed information of a launch service.
     *
     * @param key Launch service key (uid, serviceName, moduleName).
     * @param callback Callback to receive the result and queried service info.
     */
    virtual void GetLaunchServiceInfo(int32_t uid, const std::optional<LaunchServiceKey> &key,
        const std::shared_ptr<LaunchServiceListCallback> &callback) = 0;

    /**
     * @brief Obtain the list of registered launch services, optionally filtered by user.
     *
     * Each service supports a maximum of 64 registered agent/daemon instances.
     *
     * @param userId System userId, generated by account subsystem. Optional.
     * @param callback Callback to receive the result and queried service list.
     */
    virtual void GetLaunchServiceList(const std::optional<int32_t> &userId,
        const std::shared_ptr<LaunchServiceListCallback> &callback) = 0;

    /**
     * @brief Set the active state of a launch service.
     *
     * @param uid Caller uid.
     * @param token Admin authorization token.
     * @param activeState Target active state.
     * @param callback Callback to receive the result.
     */
    virtual void SetLaunchServiceState(int32_t uid, const std::vector<uint8_t> &token,
        LaunchServiceState activeState, const std::shared_ptr<LaunchServiceCallback> &callback) = 0;

    /**
     * @brief Set the allowed list for daemon services.
     *
     * If both allowed list and forbidden list are set, only the allowed list takes effect.
     * When userId is 0, the configuration applies globally.
     *
     * @param userId System userId. Use 0 for global configuration.
     * @param appIdentifiers List of app identifiers to allow.
     * @param isAdd Whether the apps are allowed.
     * @return Return set result(0:success; other:failed).
     */
    virtual int32_t SetDaemonAllowedlist(int32_t userId, const std::vector<std::string> &appIdentifiers,
        bool isAdd) = 0;

    /**
     * @brief Set the forbidden list for daemon services.
     *
     * If both allowed list and forbidden list are set, only the allowed list takes effect.
     * When userId is 0, the configuration applies globally.
     *
     * @param userId System userId. Use 0 for global configuration.
     * @param appIdentifiers List of app identifiers to forbid.
     * @param isAdd Whether the apps are forbidden.
     * @return Return set result(0:success; other:failed).
     */
    virtual int32_t SetDaemonForbiddenlist(int32_t userId, const std::vector<std::string> &appIdentifiers,
        bool isAdd) = 0;
};
} // namespace UserAuth
} // namespace UserIam
} // namespace OHOS
#endif // USER_LAUNCH_SERVICE_H
